	SELECT  cohort_year_month
			,month_n
			,COUNT(DISTINCT customer_unique_id) AS buyers
	  FROM  olist_am.vw_base_customer_monthly_purchase
	 WHERE  cohort_year_month BETWEEN '2017-01' AND '2018-08'
	   AND  month_n <= 6
	 GROUP
	    BY  cohort_year_month
	    	,month_n
)
SELECT  b.cohort_year_month
		,b.month_n
		,b.buyers
		,s.cohort_size
		,b.buyers / s.cohort_size AS retention_rate
  FROM  cohort_buyers AS b
  JOIN  cohort_size AS s
    ON  s.cohort_year_month = b.cohort_year_month
 ORDER
    BY  b.cohort_year_month
    	,b.month_n;





















