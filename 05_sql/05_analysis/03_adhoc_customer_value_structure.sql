WITH rnk AS (
	SELECT  `year_month`
			,customer_unique_id
			,gross_revenue
			,PERCENT_RANK() OVER (PARTITION BY `year_month` ORDER BY gross_revenue DESC) AS pr
	  FROM  olist_am.vw_base_customer_monthly_purchase
	 WHERE  `year_month` BETWEEN '2017-01' AND '2018-08'
)
SELECT  `year_month`
		,SUM(gross_revenue) AS total_revenue
		,SUM(CASE WHEN pr <= 0.01 THEN gross_revenue END) AS top1_revenue
		,SUM(CASE WHEN pr <= 0.01 THEN gross_revenue END) / NULLIF(SUM(gross_revenue), 0) AS top1_revenue_share
		,COUNT(*) AS buyers
		,SUM(CASE WHEN pr <= 0.01 THEN 1 END) AS top1_buyers
  FROM  rnk
 GROUP
    BY  `year_month`
 ORDER
    BY  `year_month`;


