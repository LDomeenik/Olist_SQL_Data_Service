WITH cohort_size AS (
	SELECT  first_purchase_year_month AS cohort_year_month
			,COUNT(*) AS cohort_size
	  FROM  olist_dm.vw_customer_first_purchase_month
	 WHERE  first_purchase_year_month BETWEEN '2017-01' AND '2018-08'
	 GROUP
	    BY  first_purchase_year_month
