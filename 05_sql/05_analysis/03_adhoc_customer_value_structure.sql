WITH base AS (
	SELECT  `year_month`
			,gross_revenue
			,order_cnt
			,active_buyers
			,aov
			,gross_revenue / NULLIF(active_buyers, 0) AS arpb
			,order_cnt / NULLIF(active_buyers, 0) AS orders_per_buyer
	  FROM  olist_am.vw_kpi_monthly_core
	 WHERE  `year_month` BETWEEN '2017-01' AND '2018-08'
),
mom AS (
	SELECT  *
			,(gross_revenue - LAG(gross_revenue) OVER (ORDER BY `year_month`)) / NULLIF(LAG(gross_revenue) OVER (ORDER BY `year_month`), 0) AS mom_rev
			,(arpb - LAG(arpb) OVER (ORDER BY `year_month`)) / NULLIF(LAG(arpb) OVER (ORDER BY `year_month`), 0) AS mom_arpb
			,(orders_per_buyer - LAG(orders_per_buyer) OVER (ORDER BY `year_month`)) / NULLIF(LAG(orders_per_buyer) OVER (ORDER BY `year_month`), 0) AS mom_opb
			,(aov - LAG(aov) OVER (ORDER BY `year_month`)) / NULLIF(LAG(aov) OVER (ORDER BY `year_month`), 0) AS mom_aov
	  FROM  base
)
SELECT  `year_month`
		,gross_revenue
		,mom_rev
		,arpb
		,mom_arpb
		,orders_per_buyer
		,mom_opb
		,aov
		,mom_aov
  FROM  mom
 ORDER
    BY  `year_month`;


