WITH rnk AS (
	SELECT  `year_month`
			,customer_unique_id
			,gross_revenue
			,NTILE(10) OVER (PARTITION BY `year_month` ORDER BY gross_revenue DESC) AS decile
	  FROM  olist_am.vw_base_customer_monthly_purchase
	 WHERE  `year_month` BETWEEN '2017-01' AND '2018-08'
),
agg AS (
	SELECT  `year_month`
			,decile
			,SUM(gross_revenue) AS revenue
	  FROM  rnk
	 GROUP
	    BY  `year_month`
	    	,decile
),
total AS (
	SELECT  `year_month`
			,SUM(revenue) AS total_revenue
	  FROM  agg
	 GROUP
	    BY  `year_month`
)
SELECT  a.`year_month`
		,a.decile
		,a.revenue
		,a.revenue / NULLIF(t.total_revenue, 0) AS revenue_share
  FROM  agg AS a
  JOIN  total AS t
    ON  t.`year_month` = a.`year_month`
 WHERE  a.`year_month` IN ('2017-11', '2017-12')
 ORDER
    BY  a.`year_month`
    	,a.decile;


