WITH rnk AS (
	SELECT  `year_month`
			,customer_unique_id
			,gross_revenue
			,NTILE(10) OVER (PARTITION BY `year_month` ORDER BY gross_revenue DESC) AS decile
	  FROM  olist_am.vw_base_customer_monthly_purchase
	 WHERE  `year_month` BETWEEN '2017-01' AND '2018-08'
)
SELECT  `year_month`
		,SUM(gross_revenue) AS total_revenue
		,SUM(CASE WHEN decile = 1 THEN gross_revenue END) AS top10_revenue
		,SUM(CASE WHEN decile =1 THEN gross_revenue END) / NULLIF(SUM(gross_revenue), 0) AS top10_revenue_share
  FROM  rnk
 GROUP
    BY  `year_month`
 ORDER
    BY  `year_month`;


